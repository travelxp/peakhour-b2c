/**
 * Generates src/lib/seo/candidates.ts from docs/seo/page-audit-v2.csv.
 *
 *   npx tsx scripts/seo/import-candidates.ts          # rewrite the file
 *   npx tsx scripts/seo/import-candidates.ts --check  # exit 1 if the file is stale
 *
 * `renderCandidates` is pure so a unit test can prove the committed file equals its output.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

export const CSV_PATH = "docs/seo/page-audit-v2.csv";
export const OUT_PATH = "src/lib/seo/candidates.ts";

/** RFC 4180 parser: quoted fields, doubled quotes, newlines inside quotes. */
export function parseCsv(text: string): string[][] {
  const rows: string[][] = [];
  let row: string[] = [];
  let field = "";
  let quoted = false;
  const src = text.replace(/^﻿/, "");
  for (let i = 0; i < src.length; i++) {
    const c = src[i];
    if (quoted) {
      if (c === '"') {
        if (src[i + 1] === '"') {
          field += '"';
          i++;
        } else quoted = false;
      } else field += c;
    } else if (c === '"') quoted = true;
    else if (c === ",") {
      row.push(field);
      field = "";
    } else if (c === "\n" || c === "\r") {
      if (c === "\r" && src[i + 1] === "\n") i++;
      row.push(field);
      field = "";
      if (row.some((f) => f !== "")) rows.push(row);
      row = [];
    } else field += c;
  }
  if (field !== "" || row.length) {
    row.push(field);
    if (row.some((f) => f !== "")) rows.push(row);
  }
  return rows;
}

const COLUMNS = ["id", "path_v2", "family", "scope", "priority_v2", "verdict", "merge_into", "evidence", "audit_note"] as const;

export function renderCandidates(csvText: string): string {
  const [header, ...body] = parseCsv(csvText);
  const idx = Object.fromEntries(COLUMNS.map((c) => [c, header.indexOf(c)]));
  for (const c of COLUMNS) if (idx[c] < 0) throw new Error(`${CSV_PATH} has no "${c}" column`);
  const items = body.map((r) => {
    const get = (c: (typeof COLUMNS)[number]) => r[idx[c]] ?? "";
    return {
      pageId: get("id"),
      path: get("path_v2"),
      family: get("family"),
      scope: get("scope"),
      priority: get("priority_v2"),
      verdict: get("verdict"),
      mergeInto: get("merge_into"),
      evidence: get("evidence"),
      auditNote: get("audit_note"),
    };
  });
  const lines = items.map((it) => `  ${JSON.stringify(it)},`);
  return `// GENERATED by scripts/seo/import-candidates.ts from docs/seo/page-audit-v2.csv. Do not edit by hand:
// edit the CSV and run \`npx tsx scripts/seo/import-candidates.ts\`. A test fails when this file is stale.
//
// Candidates are the audit's ${items.length} rows. They never render and never reach the sitemap: a page exists only
// when it is in pages.ts.
import type { PageFamily } from "./types";

export type CandidateVerdict = "keep" | "keep-draft" | "change" | "defer" | "drop" | "merge" | "add";
export type CandidateScope = "global" | "shopify" | "platform";
export type CandidatePriority = "P0" | "P1" | "P2";

export type Candidate = {
  pageId: string;
  /** The audit's path_v2: where the page goes if it is built. */
  path: string;
  family: PageFamily;
  scope: CandidateScope;
  priority: CandidatePriority;
  verdict: CandidateVerdict;
  /** The pageId this row folds into, when verdict is "merge". */
  mergeInto: string;
  evidence: string;
  auditNote: string;
};

export const CANDIDATES: readonly Candidate[] = [
${lines.join("\n")}
] as readonly Candidate[];
`;
}

function main() {
  const root = resolve(dirname(fileURLToPath(import.meta.url)), "..", "..");
  const out = renderCandidates(readFileSync(resolve(root, CSV_PATH), "utf8"));
  const target = resolve(root, OUT_PATH);
  if (process.argv.includes("--check")) {
    if (readFileSync(target, "utf8") !== out) {
      console.error(`${OUT_PATH} is stale. Run: npx tsx scripts/seo/import-candidates.ts`);
      process.exit(1);
    }
    return;
  }
  writeFileSync(target, out);
  console.log(`wrote ${OUT_PATH}`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
