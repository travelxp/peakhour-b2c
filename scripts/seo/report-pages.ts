/**
 * The page table of docs/seo/IMPLEMENTATION_GAPS.md, generated from the registry so it can be re-run.
 *
 *   npx tsx scripts/seo/report-pages.ts            print the table
 *   npx tsx scripts/seo/report-pages.ts --write    rewrite the table between the markers in the gap report
 *
 * report-pages.test.ts fails when the committed table is not what the registry produces now.
 */

import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { PAGES } from "../../src/lib/seo/pages";
import { isPublishable } from "../../src/lib/seo/publish";
import type { PageRecord } from "../../src/lib/seo/types";

export const BEGIN = "<!-- pages:begin (generated by scripts/seo/report-pages.ts; do not edit by hand) -->";
export const END = "<!-- pages:end -->";

function status(p: PageRecord): string {
  if (p.editorialStatus === "published" && isPublishable(p)) return "published";
  if (p.editorialStatus === "published") return "published but gated (claim not satisfied)";
  return p.editorialStatus;
}

/** One row per registry page, in registry order, with a one-line summary above it. */
export function pagesTable(pages: readonly PageRecord[] = PAGES): string {
  const published = pages.filter((p) => status(p) === "published").length;
  const lines = [
    `${pages.length} pages in the registry: ${published} published and indexable, ${pages.length - published} held in review (a draft ribbon on dev, a 404 on production).`,
    "",
    "| Path | Family | Status | Capability claims it rests on |",
    "|---|---|---|---|",
  ];
  for (const p of pages) {
    const claims = p.capabilityIds.length ? p.capabilityIds.map((c) => `\`${c}\``).join(", ") : "none (no capability claim)";
    lines.push(`| \`${p.path}\` | ${p.family} | ${status(p)} | ${claims} |`);
  }
  return lines.join("\n");
}

/** `doc` with the text between the markers replaced by `table`; throws when a marker is missing. */
export function withTable(doc: string, table: string): string {
  const eol = doc.includes("\r\n") ? "\r\n" : "\n";
  const a = doc.indexOf(BEGIN);
  const b = doc.indexOf(END);
  if (a < 0 || b < a) throw new Error("the gap report has no pages:begin / pages:end markers");
  return `${doc.slice(0, a + BEGIN.length)}${eol}${eol}${table.replace(/\n/g, eol)}${eol}${eol}${doc.slice(b)}`;
}

export const REPORT_PATH = path.resolve(__dirname, "../../docs/seo/IMPLEMENTATION_GAPS.md");

if (require.main === module) {
  if (process.argv.includes("--write")) {
    writeFileSync(REPORT_PATH, withTable(readFileSync(REPORT_PATH, "utf8"), pagesTable()));
    console.log(`wrote ${PAGES.length} rows to ${REPORT_PATH}`);
  } else {
    console.log(pagesTable());
  }
}
